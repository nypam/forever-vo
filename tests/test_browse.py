def make_pack(
    addons: Path,
    folder: str,
    *,
    priority: int = 100,
    version: str = "2026.10.18",
    tables: dict[str, str] | None = None,
    files: list[str] | tuple[str, ...] = (),
) -> Path:
    """A ForeverVO_Data* folder as release_pack.py writes it: Data/Pack.lua, the
    given Data tables, and an empty file under Sounds/ for each path in `files`."""
    root = addons / folder
    (root / "Data").mkdir(parents=True)
    (root / "Sounds").mkdir()
    (root / "Data" / "Pack.lua").write_text(
        f"-- Generated by tools/release_pack.py\n{folder}Pack = {{\n"
        f'    name = "{folder.removeprefix("ForeverVO_Data_")}",\n'
        f'    version = "{version}",\n'
        f"    priority = {priority},\n"
        f'    folder = "{folder}",\n}}\n',
        encoding="utf-8",
    )
    for name, source in (tables or {}).items():
        (root / "Data" / name).write_text(source, encoding="utf-8")
    for rel in files:
        path = root / "Sounds" / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(b"")
    return root


def lua(field: str, body: str) -> str:
    """One generated pack table file holding `pack.<field> = <body>`."""
    return (
        "-- Generated by tools/generate.py; do not edit.\n"
        "local pack = ForeverVO_DataPack\n"
        f"pack.{field} = {body}\n"
    )


def test_parse_value_reads_pack_assignment():
    assert parse_value('{ [2] = { a=16.6, va="narrator" }, [5] = { c=5.1 } }') == {
        2: {"a": 16.6, "va": "narrator"},
        5: {"c": 5.1},
    }


def test_find_packs_order(tmp_path):
    make_pack(tmp_path, "ForeverVO_Data_B", priority=100)
    make_pack(tmp_path, "ForeverVO_Data_A", priority=100)
    make_pack(tmp_path, "ForeverVO_Data_Old", priority=50)
    (tmp_path / "ForeverVO").mkdir()  # the player addon, not a pack
    (tmp_path / "ForeverVO_Data_NoSounds" / "Data").mkdir(parents=True)
    packs = find_packs(tmp_path)
    assert [p.folder for p in packs] == [
        "ForeverVO_Data_A",
        "ForeverVO_Data_B",
        "ForeverVO_Data_Old",
    ]
    assert (packs[2].label, packs[2].version, packs[2].priority) == (
        "Old",
        "2026.10.18",
        50,
    )
    assert find_packs(None) == []
    assert find_packs(tmp_path / "nope") == []


def test_read_tables_merges_fields(tmp_path):
    make_pack(
        tmp_path,
        "ForeverVO_Data_X",
        tables={
            "Quests.lua": lua(
                "quests",
                '{\n\t[7] = { a=13.1, va="human-male-official", npc=197 },\n}',
            ),
            "Narrator.lua": (
                "local pack = ForeverVO_DataPack\n"
                'pack.narratorVoices = { "skyborne-female" }\n'
                "pack.narrator = {\n\t[2] = { [1]={ a=18.7 } },\n}\n"
            ),
        },
    )
    tables = read_tables(find_packs(tmp_path)[0])
    assert tables["quests"][7]["npc"] == 197
    assert tables["narrator"][2] == [{"a": 18.7}]  # { [1]=... } parses as a list too
    assert tables["narratorVoices"] == [
        "skyborne-female"
    ]  # positional tables are lists
    assert "gossip" not in tables


def rows(addons: Path) -> dict[str, Line]:
    return {line.id: line for line in merge(find_packs(addons))}


def quest_pack(addons: Path, body: str, files=(), narrator: str = "", **kw) -> Path:
    tables = {"Quests.lua": lua("quests", body)}
    if narrator:
        tables["Narrator.lua"] = (
            "local pack = ForeverVO_DataPack"
            + chr(10)
            + 'pack.narratorVoices = { "skyborne-female" }'
            + chr(10)
            + f"pack.narrator = {narrator}"
            + chr(10)
        )
    return make_pack(
        addons, kw.pop("folder", "ForeverVO_Data_X"), tables=tables, files=files, **kw
    )


def test_quest_events_and_speakers(tmp_path):
    quest_pack(
        tmp_path,
        '{ [7] = { a=13.1, va="v1", npc=197, c=13.6, vc="v2", ender=250 } }',
        files=["Quests/7-accept.mp3", "Quests/7-complete.mp3"],
    )
    found = rows(tmp_path)
    accept, complete = found["q:7:accept"], found["q:7:complete"]
    assert accept.speaker == 197 and accept.files == ["Quests/7-accept.mp3"]
    assert accept.kind == "accept" and accept.quest_id == 7 and accept.duration == 13.1
    assert complete.speaker == 250 and complete.voice == "v2"
    assert "q:7:progress" not in found


def test_parts_play_in_order(tmp_path):
    quest_pack(
        tmp_path,
        '{ [9] = { c=3.0, vc="v", cP = { { d=1.1 }, { d=1.4, n=true }, { d=0.6 } } } }',
        files=[f"Quests/9-p{i}-complete.mp3" for i in (1, 2, 3)],
    )
    line = rows(tmp_path)["q:9:complete"]
    assert line.files == [
        "Quests/9-p1-complete.mp3",
        "Quests/9-p2-complete.mp3",
        "Quests/9-p3-complete.mp3",
    ]
    assert line.path == "Quests/9-complete.mp3"
    assert line.duration == pytest.approx(3.1)
    assert not line.missing


