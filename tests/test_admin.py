def compare_dir(tmp_path: Path, *paths: str) -> Path:
    root = tmp_path / "talk2me"
    for rel in paths:
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_bytes(b"")
    return root


